"""Minimal FDM G-code writer, parser and splicer.

Writer: perimeters (offset loops) + alternating-angle solid hatch, so any region
can be turned into printable layers. Markers (";LAYER_CHANGE", ";Z:", ";HEIGHT:",
";WIDTH:") are the ones Bambu Studio / Orca / Prusa emit, so the parser reads Bambu Studio
output directly (G1 and G2/G3 arcs, relative or absolute E). In Bambu Studio, turn off
"Arc fitting" anyway if you can: straight segments are simpler to verify.

`origin` is where the part centre sits on the bed (mm); parse subtracts it and write adds it,
so everything inside the pipeline is centred on (0, 0).
"""
import re
from typing import List, Tuple

import numpy as np
import shapely
from shapely.geometry import LineString, MultiLineString

from . import config as C
from .geometry.ops import polys
from .types import Layer

HEADER = """; generated by recovery.gcode
M140 S60
M104 S210
G28
M190 S60
M109 S210
G21
G90
M83
G92 E0
"""
FOOTER = """M104 S0
M140 S0
G91
G1 Z10 F600
G90
M84
; end
"""


def _e(length, w, h):
    return length * w * h / C.FILAMENT_AREA


def layer_paths(region, layer_idx, w=C.LINE_W, loops=2) -> List[np.ndarray]:
    """Polylines (mm, centred coords) that fill `region`."""
    paths = []
    for i in range(loops):
        g = region.buffer(-(i + 0.5) * w, quad_segs=8)
        for p in polys(g):
            paths.append(np.array(p.exterior.coords))
            paths.extend(np.array(r.coords) for r in p.interiors)
    inner = region.buffer(-loops * w + 0.05, quad_segs=8)
    if not inner.is_empty:
        ang = np.deg2rad(45 if layer_idx % 2 == 0 else 135)
        d = np.array([np.cos(ang), np.sin(ang)])
        n = np.array([-d[1], d[0]])
        minx, miny, maxx, maxy = inner.bounds
        R = np.hypot(maxx - minx, maxy - miny) / 2 + 1
        c = np.array([(minx + maxx) / 2, (miny + maxy) / 2])
        lines = [LineString([c + n * s - d * R, c + n * s + d * R])
                 for s in np.arange(-R, R, w)]
        hatch = MultiLineString(lines).intersection(inner)
        segs = [hatch] if isinstance(hatch, LineString) else list(getattr(hatch, "geoms", []))
        flip = False
        for s in segs:
            if isinstance(s, LineString) and s.length > 0.2:
                a = np.array(s.coords)
                paths.append(a[::-1] if flip else a)
                flip = not flip
    return paths


def write_layers(layers: List[Layer], layer_h, start_idx=0, w=C.LINE_W, loops=2,
                 feed=1800, origin=None, bambu=False) -> Tuple[str, float]:
    """G-code text for the layers; returns (text, filament_mm).
    bambu=True also emits `M73 L<n>` (layer progress) so the printer's reported
    layer_num keeps counting through adapted layers."""
    out, filament = [], 0.0
    cx, cy = origin or C.BED_CENTER
    for k, lay in enumerate(layers):
        out += [";LAYER_CHANGE", f";Z:{lay.z:.3f}", f";HEIGHT:{layer_h:.3f}", f";WIDTH:{w:.3f}"]
        if bambu:
            out.append(f"M73 L{start_idx + k + 1}")
        out.append(f"G1 Z{lay.z:.3f} F600")
        for path in layer_paths(lay.region, start_idx + k, w, loops):
            out.append(f"G0 X{path[0,0]+cx:.3f} Y{path[0,1]+cy:.3f} F7200")
            for a, b in zip(path[:-1], path[1:]):
                e = _e(np.hypot(*(b - a)), w, layer_h)
                filament += e
                out.append(f"G1 X{b[0]+cx:.3f} Y{b[1]+cy:.3f} E{e:.5f} F{feed}")
    return "\n".join(out) + "\n", filament


def write_gcode(layers, layer_h, **kw) -> Tuple[str, float]:
    body, fil = write_layers(layers, layer_h, **kw)
    return HEADER + body + FOOTER, fil


_NUM = re.compile(r"([XYZEFIJR])(-?\d+\.?\d*)")


def _arc(x, y, nx, ny, v, cw):
    """Points along a G2/G3 arc from (x,y) to (nx,ny); centre = start + (I,J).
    Start == end means a full circle. (Radius-form arcs are not emitted by Bambu Studio.)"""
    ccx, ccy = x + v.get("I", 0.0), y + v.get("J", 0.0)
    r = np.hypot(x - ccx, y - ccy)
    a0, a1 = np.arctan2(y - ccy, x - ccx), np.arctan2(ny - ccy, nx - ccx)
    full = abs(nx - x) < 1e-6 and abs(ny - y) < 1e-6
    if cw:
        if a1 >= a0 or full:
            a1 -= 2 * np.pi
    elif a1 <= a0 or full:
        a1 += 2 * np.pi
    n = max(int(abs(a1 - a0) / np.deg2rad(5)), 1)
    ang = np.linspace(a0, a1, n + 1)[1:]
    return [(ccx + r * np.cos(t), ccy + r * np.sin(t)) for t in ang[:-1]] + [(nx, ny)]


def parse_gcode(text: str, default_w=C.LINE_W, origin=None):
    """-> list of (z, [polylines]) for every layer, centred coordinates."""
    cx, cy = origin or C.BED_CENTER
    x = y = z = e = 0.0
    rel_e = False
    layers, cur = [], None
    width = default_w
    for line in text.splitlines():
        s = line.split(";", 1)
        cmt = s[1].strip() if len(s) > 1 else ""
        code = s[0].strip()
        if cmt.startswith("LAYER_CHANGE"):
            cur = [None, []]
            layers.append(cur)
        elif cmt.startswith("Z:") and cur is not None:
            cur[0] = float(cmt[2:])
        elif cmt.startswith("WIDTH:"):
            width = float(cmt[6:])
        if not code:
            continue
        op = code.split()[0]
        if op == "M82":
            rel_e = False
        elif op == "M83":
            rel_e = True
        elif op == "G92":
            v = dict(_NUM.findall(code))
            if "E" in v:
                e = float(v["E"])
        elif op in ("G0", "G1", "G2", "G3"):
            v = {k: float(a) for k, a in _NUM.findall(code)}
            nx, ny = v.get("X", x), v.get("Y", y)
            ne = (v["E"] if rel_e else v["E"] - e) if "E" in v else 0.0
            if "E" in v and not rel_e:
                e = v["E"]
            if "Z" in v:
                z = v["Z"]
            is_arc = op in ("G2", "G3") and ("I" in v or "J" in v)
            if ne > 0 and cur is not None and (nx != x or ny != y or is_arc):
                pts = [(x, y)]
                if is_arc:
                    pts += _arc(x, y, nx, ny, v, cw=(op == "G2"))
                else:
                    pts.append((nx, ny))
                a = np.array(pts) - np.array([cx, cy])
                cur[1].extend(a[i:i + 2] for i in range(len(a) - 1))
            x, y = nx, ny
    out = []
    for zz, segs in layers:
        out.append((zz if zz is not None else z, segs))
    return out, width


def gcode_to_layers(text: str, origin=None) -> List[Layer]:
    """Reconstruct the deposited region of every layer from its extrusion moves."""
    raw, w = parse_gcode(text, origin=origin)
    layers = []
    for z, segs in raw:
        if not segs:
            layers.append(Layer(z, shapely.Polygon()))
            continue
        lines = shapely.multilinestrings([shapely.linestrings(s) for s in segs])
        region = shapely.union_all(shapely.buffer(shapely.get_parts(lines), w / 2, quad_segs=2))
        from .geometry.ops import clean
        layers.append(Layer(z, clean(region)))
    return layers


def print_settings(text: str, default_nozzle=220, default_bed=55) -> dict:
    """Temperatures from the config block Bambu Studio appends to its G-code."""
    def grab(keys, default):
        for k in keys:
            m = re.search(rf"^;\s*{k}\s*=\s*(\d+)", text, re.M)
            if m:
                return int(m.group(1))
        return default
    return dict(nozzle=grab(["nozzle_temperature"], default_nozzle),
                bed=grab(["hot_plate_temp", "textured_plate_temp", "cool_plate_temp",
                          "eng_plate_temp"], default_bed))


def splice_gcode(original: str, keep_layers: int, new_layers: List[Layer], layer_h,
                 origin=None) -> Tuple[str, float]:
    """Keep the first `keep_layers` layers of `original`, append `new_layers`."""
    lines = original.splitlines()
    idx = [i for i, l in enumerate(lines) if l.startswith(";LAYER_CHANGE")]
    cut = idx[keep_layers] if keep_layers < len(idx) else len(lines)
    head = "\n".join(lines[:cut]) + "\n"
    body, fil = write_layers(new_layers, layer_h, start_idx=keep_layers, origin=origin)
    return head + "G92 E0\n; --- adapted layers ---\n" + body + FOOTER, fil
