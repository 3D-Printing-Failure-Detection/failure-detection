"""Minimal FDM G-code writer, parser and splicer.

Writer: perimeters (offset loops) + alternating-angle solid hatch, so any region
can be turned into printable layers. It emits Prusa/Orca-style markers (";LAYER_CHANGE",
";Z:", ";HEIGHT:", ";WIDTH:", ";TYPE:").

Parser: reads those and Bambu Studio's own markers ("; CHANGE_LAYER", "; Z_HEIGHT:",
"; LINE_WIDTH:", "; FEATURE:"), G1 and G2/G3 arcs, relative or absolute E. Extrusions of
non-part features (skirt, brim, prime/wipe tower, support) are ignored. When the slicer
labels its outer walls, a layer's region is rebuilt from those closed loops (even-odd fill),
so sparse infill does not punch fake holes into it; otherwise every extrusion line is
thickened to its width. In Bambu Studio, turn off "Arc fitting" anyway if you can: straight
segments are simpler to verify. Check a real export with `python -m recovery.cli check-gcode`.

`origin` is where the part centre sits on the bed (mm); parse subtracts it and write adds it,
so everything inside the pipeline is centred on (0, 0).
"""
import re
from typing import List, Tuple

import numpy as np
import shapely
from shapely.geometry import LineString, MultiLineString, Polygon

from . import config as C
from .geometry.ops import clean, polys
from .types import Layer

HEADER = """; generated by recovery.gcode
M140 S60
M104 S210
G28
M190 S60
M109 S210
G21
G90
M83
G92 E0
"""
FOOTER = """M104 S0
M140 S0
G91
G1 Z10 F600
G90
M84
; end
"""


def _e(length, w, h):
    return length * w * h / C.FILAMENT_AREA


def layer_paths(region, layer_idx, w=C.LINE_W, loops=2, tagged=False):
    """Polylines (mm, centred coords) that fill `region`.
    tagged=True returns (feature, polyline) pairs instead."""
    paths = []
    for i in range(loops):
        g = region.buffer(-(i + 0.5) * w, quad_segs=8)
        tag = "Outer wall" if i == 0 else "Inner wall"
        for p in polys(g):
            paths.append((tag, np.array(p.exterior.coords)))
            paths.extend((tag, np.array(r.coords)) for r in p.interiors)
    inner = region.buffer(-loops * w + 0.05, quad_segs=8)
    if not inner.is_empty:
        ang = np.deg2rad(45 if layer_idx % 2 == 0 else 135)
        d = np.array([np.cos(ang), np.sin(ang)])
        n = np.array([-d[1], d[0]])
        minx, miny, maxx, maxy = inner.bounds
        R = np.hypot(maxx - minx, maxy - miny) / 2 + 1
        c = np.array([(minx + maxx) / 2, (miny + maxy) / 2])
        lines = [LineString([c + n * s - d * R, c + n * s + d * R])
                 for s in np.arange(-R, R, w)]
        hatch = MultiLineString(lines).intersection(inner)
        segs = [hatch] if isinstance(hatch, LineString) else list(getattr(hatch, "geoms", []))
        flip = False
        for s in segs:
            if isinstance(s, LineString) and s.length > 0.2:
                a = np.array(s.coords)
                paths.append(("Solid infill", a[::-1] if flip else a))
                flip = not flip
    return paths if tagged else [p for _, p in paths]


def gap_fill_paths(region, paths, w=C.LINE_W, min_gap=0.15):
    """Strips of `region` that the line paths (each `w` wide) leave empty, e.g. the middle of a
    wall thinner than four line widths. Returns (polyline, width) along each strip's middle."""
    if not paths:
        return []
    covered = shapely.union_all([LineString(p).buffer(w / 2, quad_segs=4) for p in paths if len(p) > 1])
    out = []
    for strip in polys(clean(region.difference(covered.buffer(0.01)))):
        width = 2 * strip.area / max(strip.length, 1e-9)          # a thin strip: area ~ length x width
        if width < min_gap or width > 2 * w:
            continue
        for mid in polys(strip.buffer(-0.45 * width, quad_segs=4)):
            if mid.interiors:                       # a closed ring of gap: one loop along its middle
                out.append((np.array(mid.exterior.coords), width))
                continue
            # an open strip: one line along its long axis (tracing the outline would extrude it twice)
            r = np.array(mid.minimum_rotated_rectangle.exterior.coords)[:4]
            sides = [(r[i], r[(i + 1) % 4]) for i in range(4)]
            short = sorted(sides, key=lambda s: np.hypot(*(s[1] - s[0])))[:2]
            out.append((np.array([(short[0][0] + short[0][1]) / 2, (short[1][0] + short[1][1]) / 2]), width))
    return out


def write_layers(layers: List[Layer], layer_h, start_idx=0, w=C.LINE_W, loops=2,
                 feed=1800, origin=None, bambu=False, gap_fill=False, retract_mm=0.0,
                 zhop_mm=0.0) -> Tuple[str, float]:
    """G-code text for the layers; returns (text, filament_mm).
    bambu=True also emits `M73 L<n>` (layer progress) so the printer's reported
    layer_num keeps counting through adapted layers. For G-code that a real printer will run
    (the defaults keep the simulator's output unchanged): gap_fill extrudes the empty middle of
    thin walls; retract_mm pulls the filament back before each travel; zhop_mm opens the gap
    between nozzle and part during travel (on the P1S the bed drops, the nozzle stays put)."""
    out, filament = [], 0.0
    cx, cy = origin or C.BED_CENTER
    for k, lay in enumerate(layers):
        out += [";LAYER_CHANGE", f";Z:{lay.z:.3f}", f";HEIGHT:{layer_h:.3f}", f";WIDTH:{w:.3f}"]
        if bambu:
            out.append(f"M73 L{start_idx + k + 1}")
        tagged = layer_paths(lay.region, start_idx + k, w, loops, tagged=True)
        jobs = [(feat, path, w) for feat, path in tagged]
        if gap_fill:
            jobs += [("Gap infill", path, gw) for path, gw in gap_fill_paths(lay.region, [p for _, p in tagged], w)]
        if not zhop_mm:
            out.append(f"G1 Z{lay.z:.3f} F600")
        tag = None
        for i, (feat, path, width) in enumerate(jobs):
            if feat != tag:
                out.append(f";TYPE:{feat}")
                tag = feat
            if zhop_mm:                         # lift clear, travel, come back down, prime
                if retract_mm and (i or k):
                    out.append(f"G1 E-{retract_mm:.2f} F1800")
                out.append(f"G1 Z{lay.z + zhop_mm:.3f} F600")
                out.append(f"G0 X{path[0,0]+cx:.3f} Y{path[0,1]+cy:.3f} F7200")
                out.append(f"G1 Z{lay.z:.3f} F600")
                if retract_mm and (i or k):
                    out.append(f"G1 E{retract_mm:.2f} F1800")
            else:
                if retract_mm and i:
                    out.append(f"G1 E-{retract_mm:.2f} F1800")
                out.append(f"G0 X{path[0,0]+cx:.3f} Y{path[0,1]+cy:.3f} F7200")
                if retract_mm and i:
                    out.append(f"G1 E{retract_mm:.2f} F1800")
            for a, b in zip(path[:-1], path[1:]):
                e = _e(np.hypot(*(b - a)), width, layer_h)
                filament += e
                out.append(f"G1 X{b[0]+cx:.3f} Y{b[1]+cy:.3f} E{e:.5f} F{feed}")
    return "\n".join(out) + "\n", filament


def write_gcode(layers, layer_h, **kw) -> Tuple[str, float]:
    body, fil = write_layers(layers, layer_h, **kw)
    return HEADER + body + FOOTER, fil


_NUM = re.compile(r"([XYZEFIJR])([+-]?(?:\d+(?:\.\d*)?|\.\d+))")

# Prusa/Orca (";LAYER_CHANGE", ";Z:0.4") and Bambu Studio ("; CHANGE_LAYER", "; Z_HEIGHT: 0.4");
# comments are matched after stripping the ";" and surrounding spaces
LAYER_MARKERS = ("LAYER_CHANGE", "CHANGE_LAYER")
Z_MARKERS = ("Z_HEIGHT:", "Z:")
WIDTH_MARKERS = ("LINE_WIDTH:", "WIDTH:")
FEATURE_MARKERS = ("FEATURE:", "TYPE:")
OUTER_WALL = ("outer wall", "external perimeter")
NOT_PART = ("skirt", "brim", "prime tower", "wipe tower", "support", "purge")


def _value(cmt, markers):
    for m in markers:
        if cmt.startswith(m):
            return cmt[len(m):].strip()
    return None


def is_layer_change(line: str) -> bool:
    s = line.lstrip()
    return s.startswith(";") and s[1:].strip().startswith(LAYER_MARKERS)


def _arc(x, y, nx, ny, v, cw):
    """Points along a G2/G3 arc from (x,y) to (nx,ny); centre = start + (I,J).
    Start == end means a full circle. (Radius-form arcs are not emitted by Bambu Studio.)"""
    ccx, ccy = x + v.get("I", 0.0), y + v.get("J", 0.0)
    r = np.hypot(x - ccx, y - ccy)
    a0, a1 = np.arctan2(y - ccy, x - ccx), np.arctan2(ny - ccy, nx - ccx)
    full = abs(nx - x) < 1e-6 and abs(ny - y) < 1e-6
    if cw:
        if a1 >= a0 or full:
            a1 -= 2 * np.pi
    elif a1 <= a0 or full:
        a1 += 2 * np.pi
    n = max(int(abs(a1 - a0) / np.deg2rad(5)), 1)
    ang = np.linspace(a0, a1, n + 1)[1:]
    return [(ccx + r * np.cos(t), ccy + r * np.sin(t)) for t in ang[:-1]] + [(nx, ny)]


def parse_gcode(text: str, default_w=C.LINE_W, origin=None, *, with_widths=False, with_walls=False):
    """-> (list of (z, segments) per layer, last width), centred coordinates. A segment is a
    (2, 2) array, or (array, width) with with_widths=True. with_walls=True adds a third item per
    layer: the outer-wall segments in print order (used to rebuild the layer outline)."""
    cx, cy = origin or C.BED_CENTER
    x = y = z = e = 0.0
    rel_e = False
    rel_xyz = False
    layers, cur = [], None
    width, feature = default_w, ""
    for line in text.splitlines():
        s = line.split(";", 1)
        cmt = s[1].strip() if len(s) > 1 else ""
        code = s[0].strip()
        if cmt:
            if cmt.startswith(LAYER_MARKERS):
                cur = [None, [], []]
                layers.append(cur)
            elif (v := _value(cmt, Z_MARKERS)) is not None and cur is not None:
                cur[0] = float(v)
            elif (v := _value(cmt, WIDTH_MARKERS)) is not None:
                width = float(v)
            elif (v := _value(cmt, FEATURE_MARKERS)) is not None:
                feature = v.lower()
        if not code:
            continue
        op = code.split()[0]
        if op == "G20":
            raise ValueError("inch-mode G-code is unsupported; export in millimetres (G21)")
        elif op == "G90":
            rel_xyz = False
        elif op == "G91":
            rel_xyz = True
        elif op == "M82":
            rel_e = False
        elif op == "M83":
            rel_e = True
        elif op == "G92":
            v = dict(_NUM.findall(code))
            if "E" in v:
                e = float(v["E"])
            x, y, z = float(v.get("X", x)), float(v.get("Y", y)), float(v.get("Z", z))
        elif op in ("G0", "G1", "G2", "G3"):
            v = {k: float(a) for k, a in _NUM.findall(code)}
            nx = x + v.get("X", 0) if rel_xyz else v.get("X", x)
            ny = y + v.get("Y", 0) if rel_xyz else v.get("Y", y)
            ne = (v["E"] if rel_e else v["E"] - e) if "E" in v else 0.0
            if "E" in v and not rel_e:
                e = v["E"]
            if "Z" in v:
                z = z + v["Z"] if rel_xyz else v["Z"]
            if op in ("G2", "G3") and "R" in v:
                raise ValueError("radius-form arcs are unsupported; disable arc fitting")
            is_arc = op in ("G2", "G3") and ("I" in v or "J" in v)
            if (ne > 0 and cur is not None and (nx != x or ny != y or is_arc)
                    and not feature.startswith(NOT_PART)):
                if cur[0] is None:
                    cur[0] = z
                pts = [(x, y)]
                if is_arc:
                    pts += _arc(x, y, nx, ny, v, cw=(op == "G2"))
                else:
                    pts.append((nx, ny))
                a = np.array(pts) - np.array([cx, cy])
                segs = [a[i:i + 2] for i in range(len(a) - 1)]
                cur[1].extend((g, width) if with_widths else g for g in segs)
                if feature.startswith(OUTER_WALL):
                    cur[2].extend((g, width) for g in segs)
            x, y = nx, ny
    out = [(zz if zz is not None else z, segs, walls) if with_walls else (zz if zz is not None else z, segs)
           for zz, segs, walls in layers]
    return out, width


def _rings(segs, tol):
    """Chain consecutive segments into polylines and return the closed ones as point arrays,
    or None if any chain stays open (then the walls do not describe the outline)."""
    chains = []
    for a in segs:
        if chains and np.hypot(*(chains[-1][-1] - a[0])) < 1e-3:
            chains[-1].append(a[1])
        else:
            chains.append([a[0], a[1]])
    gap = lambda c: np.hypot(*(c[-1] - c[0]))
    closed = lambda c: len(c) >= 3 and gap(c) < tol
    rings = [np.array(c) for c in chains if closed(c)]
    chains = [c for c in chains if not closed(c)]
    merged = True                                  # join pieces split by a seam or a wipe
    while merged and len(chains) > 1:
        merged = False
        for i, c in enumerate(chains):
            for j, d in enumerate(chains):
                if i != j and np.hypot(*(c[-1] - d[0])) < tol:
                    chains[i] = c + d[1:]
                    del chains[j]
                    merged = True
                    break
            if merged:
                break
    for c in chains:
        if not closed(c):
            return None
        rings.append(np.array(c))
    return rings


def _region_from_walls(walls, thick):
    """Even-odd fill of the outer-wall loops, grown by half a line width to the true edge.
    None (fall back to `thick`) when the loops do not close or do not contain the layer's
    extrusions."""
    w = float(np.mean([wd for _, wd in walls]))
    rings = _rings([g for g, _ in walls], 2 * w)
    if not rings:
        return None
    solid = Polygon()
    for p in sorted((clean(Polygon(r)) for r in rings), key=lambda g: -g.area):
        solid = solid.symmetric_difference(p)
    region = clean(solid.buffer(w / 2, quad_segs=4))
    stray = thick.difference(region.buffer(0.05)).area
    return region if stray < 0.05 * max(thick.area, 1e-9) else None


def gcode_to_layers(text: str, origin=None, stats=None) -> List[Layer]:
    """Reconstruct the deposited region of every layer from its extrusion moves. If `stats`
    (a dict) is given, it receives how many layers were rebuilt from outer walls."""
    raw, _ = parse_gcode(text, origin=origin, with_widths=True, with_walls=True)
    layers = []
    for z, segs, walls in raw:
        if not segs:
            layers.append(Layer(z, shapely.Polygon()))
            continue
        lines = [shapely.LineString(s) for s, _ in segs]
        widths = np.array([w for _, w in segs])
        thick = clean(shapely.union_all(shapely.buffer(lines, widths / 2, quad_segs=2)))
        region = _region_from_walls(walls, thick) if walls else None
        layers.append(Layer(z, region if region is not None else thick))
        if stats is not None:
            key = "from_walls" if region is not None else ("walls_fallback" if walls else "thickened")
            stats[key] = stats.get(key, 0) + 1
    return layers


def inspect_gcode(text: str, origin=None) -> dict:
    """What the parser makes of a sliced file: which markers it uses, how many layers it finds
    and how they were rebuilt. Run it on the first real export before trusting `live`/`watch`."""
    from collections import Counter
    markers, features = Counter(), Counter()
    families = (LAYER_MARKERS, Z_MARKERS, WIDTH_MARKERS, FEATURE_MARKERS)
    for line in text.splitlines():
        if ";" not in line:
            continue
        cmt = line.split(";", 1)[1].strip()
        for fam in families:
            m = next((m for m in fam if cmt.startswith(m)), None)
            if m:
                markers[m] += 1
                if fam is FEATURE_MARKERS:
                    features[cmt[len(m):].strip()] += 1
                break
    stats = {}
    layers = gcode_to_layers(text, origin=origin, stats=stats)
    solid = [l for l in layers if not l.region.is_empty]
    total = re.search(r"total layer number:\s*(\d+)", text, re.I)
    return dict(
        markers=dict(markers), features=dict(features.most_common()),
        layers_parsed=len(layers), layers_with_material=len(solid),
        empty_layers=[i for i, l in enumerate(layers) if l.region.is_empty],
        rebuild=stats, slicer_total_layers=int(total.group(1)) if total else None,
        z_first=solid[0].z if solid else None, z_last=solid[-1].z if solid else None,
        arcs=len(re.findall(r"^\s*G[23]\s", text, re.M)),
        relative_e="M83" in text, absolute_e="M82" in text,
        bounds_mm=[round(v, 2) for v in shapely.union_all([l.region for l in solid]).bounds] if solid else None)


PLATE_TEMP_KEYS = {"cool plate": "cool_plate_temp", "engineering plate": "eng_plate_temp",
                   "high temp plate": "hot_plate_temp", "textured pei plate": "textured_plate_temp"}


def print_settings(text: str, default_nozzle=220, default_bed=55) -> dict:
    """Temperatures from the config block Bambu Studio appends to its G-code. The bed temperature
    is the one for the plate the job was sliced for (`curr_bed_type`), when the file says so."""
    def grab(keys, default):
        for k in keys:
            m = re.search(rf"^;\s*{k}\s*=\s*(\d+)", text, re.M)
            if m:
                return int(m.group(1))
        return default
    plate = re.search(r"^;\s*curr_bed_type\s*=\s*(.+?)\s*$", text, re.M)
    first = PLATE_TEMP_KEYS.get(plate.group(1).lower()) if plate else None
    return dict(nozzle=grab(["nozzle_temperature"], default_nozzle),
                bed=grab(([first] if first else []) + ["hot_plate_temp", "textured_plate_temp",
                                                       "cool_plate_temp", "eng_plate_temp"], default_bed))


def splice_gcode(original: str, keep_layers: int, new_layers: List[Layer], layer_h,
                 origin=None) -> Tuple[str, float]:
    """Keep the first `keep_layers` layers of `original`, append `new_layers`."""
    lines = original.splitlines()
    idx = [i for i, l in enumerate(lines) if is_layer_change(l)]
    cut = idx[keep_layers] if keep_layers < len(idx) else len(lines)
    head = "\n".join(lines[:cut]) + "\n"
    body, fil = write_layers(new_layers, layer_h, start_idx=keep_layers, origin=origin)
    return head + "G92 E0\n; --- adapted layers ---\n" + body + FOOTER, fil
