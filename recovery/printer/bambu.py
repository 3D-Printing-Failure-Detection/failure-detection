FOOTER = "M104 S0\nM140 S0\nM84\n; end\n"


def resume_gcode(layers: List[Layer], layer_h, start_idx, origin, nozzle=220, bed=55,
                 rehome_gcode="", z_hop=0.4) -> str:
    """Self-contained G-code that continues a part from `layers` (no homing unless asked)."""
    z0 = layers[0].z if layers else 0.0
    head = [f"; resume file generated by recovery (adapted layers from index {start_idx})",
            f"M140 S{bed}", f"M104 S{nozzle}", f"M190 S{bed}", f"M109 S{nozzle}",
            "G21", "G90", "M83", "G92 E0"]
    if rehome_gcode:
        head.append(rehome_gcode)
    head += [f"G1 Z{z0 + z_hop:.3f} F600", "M106 P1 S255"]       # part-cooling fan on
    body, _ = write_layers(layers, layer_h, start_idx=start_idx, origin=origin, bambu=True)
    return "\n".join(head) + "\n" + body + FOOTER


class ImplicitFTPS(ftplib.FTP_TLS):
    """FTP over implicit TLS (port 990), which the stdlib does not do by itself."""
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self._sock = None

    @property
    def sock(self):
        return self._sock

    @sock.setter
    def sock(self, value):
        if value is not None and not isinstance(value, ssl.SSLSocket):
            value = self.context.wrap_socket(value)
        self._sock = value


def _insecure_ctx():
    ctx = ssl.create_default_context()
    ctx.check_hostname = False            # the printer uses a self-signed certificate
    ctx.verify_mode = ssl.CERT_NONE
    return ctx


def upload_ftps(ip, code, name, data: bytes, remote_dir=""):
    ftp = ImplicitFTPS(context=_insecure_ctx())
    ftp.connect(ip, 990, timeout=30)
    ftp.login("bblp", code)
    ftp.prot_p()
    if remote_dir:
        ftp.cwd(remote_dir)
    import io
    ftp.storbinary(f"STOR {name}", io.BytesIO(data))
    ftp.quit()


class BambuLink:
    """MQTT connection: merges printer reports into `.state`, publishes commands."""
    def __init__(self, ip, serial, code):
        import paho.mqtt.client as mqtt
        self.serial, self.state, self.seq = serial, {}, 0
        self.lock = threading.Lock()
        try:                                                    # paho-mqtt 2.x
            self.cli = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2)
        except AttributeError:                                  # paho-mqtt 1.x
            self.cli = mqtt.Client()
        self.cli.username_pw_set("bblp", code)
        self.cli.tls_set_context(_insecure_ctx())
        self.cli.tls_insecure_set(True)
        self.cli.on_connect = lambda c, u, f, rc, *a: c.subscribe(f"device/{serial}/report")
        self.cli.on_message = self._on_msg
        self.cli.connect(ip, 8883, 60)
        self.cli.loop_start()
        self.pushall()

    def _on_msg(self, c, u, msg):
        try:
            p = json.loads(msg.payload).get("print")
        except ValueError:
            return
        if p:
            with self.lock:
                self.state.update(p)

    def send(self, payload: dict):
        self.seq += 1
        body = next(iter(payload.values()))
        body["sequence_id"] = str(self.seq)
        self.cli.publish(f"device/{self.serial}/request", json.dumps(payload), qos=1)

    def pushall(self):
        self.send({"pushing": {"command": "pushall"}})

    def command(self, cmd, param=""):
        self.send({"print": {"command": cmd, "param": param}})

    def get(self, key, default=None):
        with self.lock:
            return self.state.get(key, default)

    def wait_state(self, states, timeout=60, poll=0.5):
        t0 = time.time()
        while time.time() - t0 < timeout:
            if self.get("gcode_state") in states:
                return True
            time.sleep(poll)
        return False


class BambuCamera:
    """P1/A1 chamber camera: TLS on port 6000, 16-byte-per-field little-endian framing."""
    def __init__(self, ip, code):
        self.ip, self.code = ip, code
        self.frame: Optional[np.ndarray] = None
        self._stop = False
        self._t = threading.Thread(target=self._run, daemon=True)
        self._t.start()

    @staticmethod
    def _recv(sock, n):
        buf = b""
        while len(buf) < n:
            chunk = sock.recv(n - len(buf))
            if not chunk:
                raise ConnectionError("camera closed")
            buf += chunk
        return buf

    def _run(self):
        while not self._stop:
            try:
                raw = socket.create_connection((self.ip, 6000), timeout=10)
                s = _insecure_ctx().wrap_socket(raw)
                s.sendall(struct.pack("<IIII", 0x40, 0x3000, 0, 0)
                          + b"bblp".ljust(32, b"\0") + self.code.encode().ljust(32, b"\0"))
                while not self._stop:
                    size = struct.unpack("<I", self._recv(s, 16)[:4])[0]
                    jpg = self._recv(s, size)
                    if jpg[:2] == b"\xff\xd8" and jpg[-2:] == b"\xff\xd9":
                        self.frame = cv2.imdecode(np.frombuffer(jpg, np.uint8), cv2.IMREAD_COLOR)
            except (OSError, ConnectionError, struct.error):
                time.sleep(2)

    def grab(self, timeout=10.0, newer_than=None):
        """Latest frame; if `newer_than` (time.time()) is given, wait for a frame after it."""
        t0 = time.time()
        last = self.frame
        while time.time() - t0 < timeout:
            if self.frame is not None and (newer_than is None or self.frame is not last):
                time.sleep(0.2)
                return self.frame.copy()
            time.sleep(0.1)
        raise TimeoutError("no camera frame (check LAN mode, access code, port 6000)")

    def close(self):
        self._stop = True


class BambuPrinter:
    def __init__(self, ip, serial, code, planned: List[Layer], layer_h, bed_camera: BedCamera,
                 origin=None, original_gcode: Optional[str] = None, mode="restart",
                 rehome_gcode="", settle_s=1.5, timeout_s=4 * 3600):
        self.ip, self.code, self.plan, self.layer_h = ip, code, list(planned), layer_h
        self.link = BambuLink(ip, serial, code)
        self.cam = BambuCamera(ip, code)
        self.bed_cam = bed_camera
        self.origin = origin or C.BED_CENTER
        self.mode, self.rehome, self.settle, self.timeout = mode, rehome_gcode, settle_s, timeout_s
        t = print_settings(original_gcode or "")
        self.nozzle, self.bed = t["nozzle"], t["bed"]
        self.cancelled = False
        self._layer = 0                  # layers finished so far (0-based count)
        self._offset = 0                 # reported layer_num -> absolute layer index correction

    # ---- helpers ----
    def _layer_num(self):
        return int(self.link.get("layer_num", 0) or 0) + self._offset

    # ---- printer interface ----
    @property
    def n_done(self):
        return self._layer

    @property
    def n_total(self):
        return len(self.plan)

    def print_layer(self):
        """Block until layer index n_done has finished: the printer reports layer_num = L
        while printing layer L (1-based), so layer i is done once layer_num >= i + 2."""
        t0 = time.time()
        while time.time() - t0 < self.timeout:
            if self._layer_num() >= self._layer + 2 or self.link.get("gcode_state") in ("FINISH", "IDLE"):
                break
            time.sleep(0.5)
        self._layer += 1
        time.sleep(self.settle)          # head parks (timelapse 'traditional') and the image settles

    def camera_image(self):
        frame = self.cam.grab()
        z = self.plan[self._layer - 1].z
        return self.bed_cam.top_down(frame, z, self.origin)

    def expected_layer(self) -> Layer:
        return self.plan[self._layer - 1]

    def pause(self):
        self.link.command("pause")
        self.link.wait_state({"PAUSE"}, timeout=60)

    def resume(self):
        self.link.command("resume")

    def replace_remaining(self, layers: List[Layer]):
        keep = self._layer
        self.plan = self.plan[:keep] + list(layers)
        gc = resume_gcode(layers, self.layer_h, keep, self.origin, self.nozzle, self.bed, self.rehome)
        if self.mode == "stream":
            lines = [l for l in gc.splitlines() if l and not l.startswith(";")]
            for i in range(0, len(lines), 20):
                self.link.command("gcode_line", "\n".join(lines[i:i + 20]))
                time.sleep(0.2)
            self.link.command("stop")
            return
        name = f"adapted_{int(time.time())}.gcode"
        self.link.command("stop")
        self.link.wait_state({"IDLE", "FINISH", "FAILED"}, timeout=120)
        upload_ftps(self.ip, self.code, name, gc.encode())
        self.link.command("gcode_file", f"/sdcard/{name}")
        self._offset = 0                                  # `M73 L<n>` in the file keeps layer_num absolute

    def cancel(self):
        self.cancelled = True
        self.link.command("stop")

    def fast_forward(self):               # not used on real hardware
        pass

    def close(self):
        self.cam.close()
        self.link.cli.loop_stop()
