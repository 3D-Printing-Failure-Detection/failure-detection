from ..types import Layer

FOOTER = "M104 S0\nM140 S0\nM84\n; end\n"


class PrintEnded(RuntimeError):
    """The job ended on the printer (stopped from the screen/app, or finished early)."""


REHOME_PRESETS = {
    "none": "",
    # re-enable the steppers, lift well clear of the part with a RELATIVE move, then home X/Y only.
    # Z is deliberately not re-homed (the nozzle would land on the part); it is assumed retained.
    "lift_xy": "M17\nG91\nG1 Z{lift:.1f} F600\nG90\nG28 X Y",
}


def resume_gcode(layers: List[Layer], layer_h, start_idx, origin, nozzle=220, bed=55,
                 rehome_gcode="", z_hop=0.4, lift_mm=10.0) -> str:
    """Self-contained G-code that continues a part from `layers`. `rehome_gcode` is raw G-code
    or the name of a preset in REHOME_PRESETS."""
    z0 = layers[0].z if layers else 0.0
    rehome_gcode = REHOME_PRESETS.get(rehome_gcode, rehome_gcode)
    if "{lift" in rehome_gcode:
        rehome_gcode = rehome_gcode.format(lift=lift_mm)
    head = [f"; resume file generated by recovery (adapted layers from index {start_idx})",
            f"M140 S{bed}", f"M104 S{nozzle}", f"M190 S{bed}", f"M109 S{nozzle}",
            "G21", "G90", "M83", "G92 E0"]
    if rehome_gcode:
        head.append(rehome_gcode)
    head += [f"G1 Z{z0 + z_hop:.3f} F600", "M106 P1 S255"]       # part-cooling fan on
    # thin walls filled, filament retracted and the bed dropped z_hop for every travel move
    body, _ = write_layers(layers, layer_h, start_idx=start_idx, origin=origin, bambu=True,
                           gap_fill=True, retract_mm=0.8, zhop_mm=z_hop)
    return "\n".join(head) + "\n" + body + FOOTER


class ImplicitFTPS(ftplib.FTP_TLS):
    """FTP over implicit TLS (port 990), which the stdlib does not do by itself."""
    def __init__(self, *a, **k):
        super().__init__(*a, **k)
        self._sock = None

    @property
    def sock(self):
        return self._sock

    @sock.setter
    def sock(self, value):
        if value is not None and not isinstance(value, ssl.SSLSocket):
            value = self.context.wrap_socket(value)
        self._sock = value


def _insecure_ctx():
    ctx = ssl.create_default_context()
    ctx.check_hostname = False            # the printer uses a self-signed certificate
    ctx.verify_mode = ssl.CERT_NONE
    return ctx


def upload_ftps(ip, code, name, data: bytes, remote_dir=""):
    ftp = ImplicitFTPS(context=_insecure_ctx())
    ftp.connect(ip, 990, timeout=30)
    ftp.login("bblp", code)
    ftp.prot_p()
    if remote_dir:
        ftp.cwd(remote_dir)
    import io
    ftp.storbinary(f"STOR {name}", io.BytesIO(data))
    ftp.quit()


class BambuLink:
    """MQTT connection: merges printer reports into `.state`, publishes commands."""
    def __init__(self, ip, serial, code):
        import paho.mqtt.client as mqtt
        self.serial, self.state, self.seq = serial, {}, 0
        self.lock = threading.Lock()
        try:                                                    # paho-mqtt 2.x
            self.cli = mqtt.Client(mqtt.CallbackAPIVersion.VERSION2)
        except AttributeError:                                  # paho-mqtt 1.x
            self.cli = mqtt.Client()
        self.cli.username_pw_set("bblp", code)
        self.cli.tls_set_context(_insecure_ctx())
        self.cli.tls_insecure_set(True)
        self.cli.on_connect = lambda c, u, f, rc, *a: c.subscribe(f"device/{serial}/report")
        self.cli.on_message = self._on_msg
        self.cli.connect(ip, 8883, 60)
        self.cli.loop_start()
        self.pushall()

    def _on_msg(self, c, u, msg):
        try:
            p = json.loads(msg.payload).get("print")
        except ValueError:
            return
        if p:
            with self.lock:
                self.state.update(p)

    def send(self, payload: dict):
        self.seq += 1
        body = next(iter(payload.values()))
        body["sequence_id"] = str(self.seq)
        self.cli.publish(f"device/{self.serial}/request", json.dumps(payload), qos=1)

    def pushall(self):
        self.send({"pushing": {"command": "pushall"}})

    def command(self, cmd, param=""):
        self.send({"print": {"command": cmd, "param": param}})

    def get(self, key, default=None):
        with self.lock:
            return self.state.get(key, default)

    def wait_state(self, states, timeout=60, poll=0.5):
        t0 = time.time()
        while time.time() - t0 < timeout:
            if self.get("gcode_state") in states:
                return True
            time.sleep(poll)
        return False


class BambuCamera:
    """P1/A1 chamber camera: TLS on port 6000, 16-byte-per-field little-endian framing."""
    def __init__(self, ip, code):
        self.ip, self.code = ip, code
        self.frame: Optional[np.ndarray] = None
        self.frame_t = 0.0                # time.time() when `frame` arrived
        self._stop = False
        self._t = threading.Thread(target=self._run, daemon=True)
        self._t.start()

    @staticmethod
    def _recv(sock, n):
        buf = b""
        while len(buf) < n:
            chunk = sock.recv(n - len(buf))
            if not chunk:
                raise ConnectionError("camera closed")
            buf += chunk
        return buf

    def _run(self):
        while not self._stop:
            try:
                raw = socket.create_connection((self.ip, 6000), timeout=10)
                s = _insecure_ctx().wrap_socket(raw)
                s.sendall(struct.pack("<IIII", 0x40, 0x3000, 0, 0)
                          + b"bblp".ljust(32, b"\0") + self.code.encode().ljust(32, b"\0"))
                while not self._stop:
                    size = struct.unpack("<I", self._recv(s, 16)[:4])[0]
                    jpg = self._recv(s, size)
                    if jpg[:2] == b"\xff\xd8" and jpg[-2:] == b"\xff\xd9":
                        self.frame = cv2.imdecode(np.frombuffer(jpg, np.uint8), cv2.IMREAD_COLOR)
                        self.frame_t = time.time()
            except (OSError, ConnectionError, struct.error):
                time.sleep(2)

    def grab(self, timeout=10.0, newer_than=None):
        """Latest frame; if `newer_than` (a time.time() value) is given, wait for a frame that
        arrived after it (the chamber camera streams only about 1 frame/s)."""
        t0 = time.time()
        while time.time() - t0 < timeout:
            frame, ft = self.frame, self.frame_t
            if frame is not None and (newer_than is None or ft > newer_than):
                return frame.copy()
            time.sleep(0.1)
        raise TimeoutError("no camera frame (check LAN mode, access code, port 6000)")

    def close(self):
        self._stop = True


class BambuPrinter:
    # defaults for attributes added after the first version, so partially built printers
    # (tests, BambuPrinter.__new__) behave like an acting printer
    observe_only = False
    skipped_layers = 0
    _seen_running = False
    _layer_done_t = 0.0
    last_frame = None
    notify_pause = False             # dent tests: return "paused" when someone else pauses the printer
    _paused_by_us = False
    _await_running = False           # after we resume, ignore the PAUSE state until RUNNING is seen

    def __init__(self, ip, serial, code, planned: List[Layer], layer_h, bed_camera: BedCamera,
                 origin=None, original_gcode: Optional[str] = None, mode="restart",
                 rehome_gcode="", settle_s=1.5, timeout_s=4 * 3600, observe_only=False):
        self.ip, self.code, self.plan, self.layer_h = ip, code, list(planned), layer_h
        if mode != "restart":
            raise ValueError("only mode='restart' is supported")
        self.observe_only = observe_only
        self.skipped_layers = 0          # observe_only: layers that finished while we were busy
        self._seen_running = False
        self._layer_done_t = 0.0         # when the last finished layer was seen to finish
        self.last_frame: Optional[np.ndarray] = None   # raw camera frame behind camera_image()
        self.printed: List[Layer] = []  # measured observations, not physical ground truth
        self.link = BambuLink(ip, serial, code)
        self.cam = BambuCamera(ip, code)
        self.bed_cam = bed_camera
        self.origin = origin or C.BED_CENTER
        self.mode, self.rehome, self.settle, self.timeout = mode, rehome_gcode, settle_s, timeout_s
        t = print_settings(original_gcode or "")
        self.nozzle, self.bed = t["nozzle"], t["bed"]
        self.cancelled = False
        self.resumed_at = None
        self._layer = 0                  # layers finished so far (0-based count)
        self._offset = 0                 # reported layer_num -> absolute layer index correction

    # ---- helpers ----
    def _layer_num(self):
        return int(self.link.get("layer_num", 0) or 0) + self._offset

    # ---- printer interface ----
    @property
    def n_done(self):
        return self._layer

    @property
    def n_total(self):
        return len(self.plan)

    def print_layer(self):
        """Block until layer index n_done has finished: the printer reports layer_num = L
        while printing layer L (1-based), so layer i is done once layer_num >= i + 2."""
        t0 = time.time()
        while time.time() - t0 < self.timeout:
            state = self.link.get("gcode_state")
            if state == "FAILED":
                raise RuntimeError("printer reports FAILED")
            if state == "RUNNING":
                self._seen_running, self._await_running = True, False
            elif (state == "PAUSE" and self.notify_pause and not self._paused_by_us
                  and not self._await_running):
                return self._external_pause()
            elif state == "IDLE" and self._seen_running:
                raise PrintEnded("the job was stopped on the printer (state IDLE)")
            reported = self._layer_num()
            if reported > self._layer + 2 and self.observe_only:
                # we were busy while layers finished: skip ahead instead of failing
                n = reported - 2 - self._layer
                self.printed.extend(self.plan[self._layer:self._layer + n])
                self._layer += n
                self.skipped_layers += n
            if state == "FINISH" and self._layer != self.n_total - 1:
                if self.observe_only:
                    raise PrintEnded(f"the printer finished at our layer {self._layer} of {self.n_total} "
                                     "(does the parsed layer count match total_layer_num?)")
                raise RuntimeError("missed completed layers; cannot reconstruct them from the latest frame")
            if reported > self._layer + 2:
                raise RuntimeError("missed completed layers; cannot reconstruct them from the latest frame")
            if reported == self._layer + 2 or state == "FINISH":
                break
            time.sleep(0.5)
        else:
            raise TimeoutError("timed out waiting for the next completed layer")
        self.printed.append(self.plan[self._layer])
        self._layer += 1
        time.sleep(self.settle)          # head parks (timelapse 'traditional') and the image settles
        self._layer_done_t = time.time()

    def _external_pause(self):
        """Someone else paused the printer: from the screen, the app, or a pause planned in Bambu
        Studio. layer_num is the layer being printed (or about to print, for a planned pause), which
        may be half done; count only the layers before it as done. (CHECK on the first real test:
        compare the layer the agent reports with the printer screen.)"""
        done = min(max(self._layer, self._layer_num() - 1), self.n_total)
        self.printed.extend(self.plan[self._layer:done])
        self._layer = done
        self._layer_done_t = time.time()
        return "paused"

    def snapshot(self):
        """Raw camera frame (as the camera sees it), newer than the last finished layer."""
        return self.cam.grab(newer_than=self._layer_done_t)

    def camera_image(self):
        frame = self.cam.grab(newer_than=self._layer_done_t)     # never a frame from mid-layer
        self.last_frame = frame
        z = self.plan[self._layer - 1].z
        return self.bed_cam.top_down(frame, z, self.origin)

    def expected_layer(self) -> Layer:
        return self.plan[self._layer - 1]

    def record_measurement(self, layer: Layer):
        self.printed[-1] = layer

    def _command_allowed(self, what):
        if self.observe_only:
            raise RuntimeError(f"observe_only: refusing to {what} the printer")

    def pause(self):
        self._command_allowed("pause")
        self._paused_by_us = True
        self.link.command("pause")
        if not self.link.wait_state({"PAUSE"}, timeout=60):
            raise TimeoutError("printer did not acknowledge pause")

    def resume(self):
        self._command_allowed("resume")
        self._paused_by_us, self._await_running = False, True
        self.link.command("resume")

    def correction_gcode(self, layers: List[Layer]) -> str:
        """The file `replace_remaining` would upload, for inspection before approving."""
        return resume_gcode(layers, self.layer_h, self._layer, self.origin, self.nozzle, self.bed, self.rehome)

    def replace_remaining(self, layers: List[Layer]):
        self._command_allowed("replace the remaining layers of")
        keep = self._layer
        self._restart(self.correction_gcode(layers), keep, layers)

    def _restart(self, gc: str, keep: int, layers: List[Layer], attempts=2):
        """Fully automatic stop -> upload -> start -> confirm. No human touches the printer.
        Retries the upload/start once; every step waits for the printer's own acknowledgement."""
        name = f"adapted_{int(time.time())}.gcode"
        self.link.command("stop")
        if not self.link.wait_state({"IDLE", "FINISH", "FAILED"}, timeout=120):
            raise TimeoutError("printer did not acknowledge stop; replacement aborted")
        last = None
        for _ in range(attempts):
            try:
                upload_ftps(self.ip, self.code, name, gc.encode())
                with self.link.lock:
                    self.link.state.pop("layer_num", None)    # so the next report is from the NEW job
                self.link.command("gcode_file", f"/sdcard/{name}")
                if not self.link.wait_state({"RUNNING"}, timeout=120):
                    raise TimeoutError("printer did not start the replacement job")
                break
            except (OSError, TimeoutError) as e:
                last = e
                self.link.pushall()
                time.sleep(3)
        else:
            raise RuntimeError(f"could not start the replacement job: {last}")
        # calibrate the layer counter from the first report of the new job: M73 L<n> may or may
        # not be honoured by the firmware, and the loop must know which layer it is looking at
        t0 = time.time()
        while self.link.get("layer_num") is None and time.time() - t0 < 180:
            time.sleep(0.5)
        first = self.link.get("layer_num")
        if first is None:
            raise TimeoutError("replacement job started but reported no layer number")
        self._offset = (keep + 1) - int(first)
        self.plan = self.plan[:keep] + list(layers)
        self.resumed_at = keep

    def cancel(self):
        self._command_allowed("stop")
        self.cancelled = True
        self.link.command("stop")

    def fast_forward(self):               # not used on real hardware
        pass

    def close(self):
        self.cam.close()
        self.link.cli.loop_stop()
