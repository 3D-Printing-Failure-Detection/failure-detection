"""Bambu Lab P1S backend. Same interface as sim.SimPrinter, so loop.controller.Controller
runs unchanged.

NOT tested on hardware. Protocol details follow the community docs (OpenBambuAPI):
  * LAN MQTT over TLS, port 8883, user `bblp`, password = LAN access code;
    commands -> device/<serial>/request, status <- device/<serial>/report
    (report fields used: gcode_state, layer_num, total_layer_num).
  * FTPS (implicit TLS) on port 990, same credentials, to upload files.
  * P1/A1-series chamber camera: TLS socket on port 6000 streaming 1280x720 JPEG frames
    (the X1 uses RTSPS on port 322 instead -- not used here).
Printer prerequisites: LAN mode on (and Developer mode, if your firmware has it, since recent
firmware restricts third-party control), the access code, the serial number, the printer's IP.

THE RISKY PART -- changing the remaining layers. A running Bambu job cannot be edited, so
`replace_remaining` does PAUSE -> STOP -> upload a self-contained 'resume' G-code (heats, no
homing/leveling, adapted layers, `M73 L<n>` so layer_num keeps counting) -> `gcode_file`.
This works only if the printer still knows its position after STOP. If it does not (steppers
released), supply `rehome_gcode` -- e.g. re-home XY and re-reference Z at a bed corner away
from the part. Never G28 over the part. Prove it on a scrap print first.

observe_only=True never sends a print command (pause, resume, stop, upload): use it for the
first runs on a real printer (`python -m recovery.cli watch`) and for collecting real images.
"""
import ftplib
import json
import socket
import ssl
import struct
import threading
import time
from typing import List, Optional

import cv2
import numpy as np

from .. import config as C
